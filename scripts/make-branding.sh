#!/bin/sh
# Writes deploy/values-branding.yaml from the image files in deploy/branding/.
# Run it after replacing a file there, then install or commit as usual.
#
# usage: scripts/make-branding.sh
set -eu

cd "$(dirname "$0")/.."
src=deploy/branding
out=deploy/values-branding.yaml
files="logo.svg favicon-16x16.png favicon-32x32.png apple-touch-icon-180x180.png"
# Helm keeps the values inside one Secret of at most 1 MiB, so the images must stay small.
max_bytes=250000

total=0
for f in $files; do
  [ -s "$src/$f" ] || { echo "missing or empty: $src/$f" >&2; exit 1; }
  total=$((total + $(wc -c < "$src/$f")))
done
if [ "$total" -gt "$max_bytes" ]; then
  echo "the files in $src are $total bytes together; the limit is $max_bytes" >&2
  exit 1
fi

{
  cat <<'HEAD'
# Generated by scripts/make-branding.sh from the files in deploy/branding/. Do not edit.
# The logo and icons go over the ones in the LibreChat image; nothing is patched.

volumes:
  - name: branding
    configMap:
      name: librechat-librechat-branding   # <release>-librechat-branding

volumeMounts:
HEAD
  for f in $files; do
    echo "  - { name: branding, mountPath: /app/client/dist/assets/$f, subPath: $f, readOnly: true }"
  done
  echo
  echo "# Changes when a file changes, so that the pod restarts with the new files."
  echo "podAnnotations:"
  echo "  govchat/branding: \"$(for f in $files; do cat "$src/$f"; done | cksum | cut -d' ' -f1)\""
  echo
  echo "additionalConfigMaps:"
  echo "  branding:"
  echo "    binaryData:"
  for f in $files; do
    echo "      $f: $(base64 < "$src/$f" | tr -d '\n')"
  done
} > "$out"

echo "wrote $out ($total bytes of images)"
